import { chromium } from 'playwright';
import { createServer } from 'http';
import { readFileSync, existsSync } from 'fs';
import { extname } from 'path';
const ROOT='D:/GPT浏览器下载/2026-10-30-10-33-22/feedudu-threejs';
const MIME={'.html':'text/html','.js':'text/javascript','.mjs':'text/javascript','.css':'text/css'};
const server=createServer((req,res)=>{let p=decodeURIComponent(req.url.split('?')[0]);if(p==='/')p='/feedudu_standalone.html';const fp=ROOT+p;if(!existsSync(fp)){res.writeHead(404);res.end();return;}res.writeHead(200,{'Content-Type':MIME[extname(fp)]||'application/octet-stream'});res.end(readFileSync(fp));});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const port=server.address().port;
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist','--enable-unsafe-swiftshader','--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:900,height:900}});
page.on('pageerror',e=>console.log('ERR',e.message));
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE-ERR',m.text());});
await page.goto(`http://127.0.0.1:${port}/feedudu_standalone.html`,{waitUntil:'networkidle',timeout:60000});
await page.waitForTimeout(4000);
await page.screenshot({path:ROOT+'/verify_standalone.png'});
const ok=await page.evaluate(()=>!!(window.__feedudu && window.__feedudu.model && window.__feedudu.model.root));
console.log('model loaded:', ok);
await browser.close();server.close();
console.log('done');
